    'garden-annex-newyork': 7,
    'sunset-forum-losangeles': 6,
    'maple-dome-toronto': 7,
    'national-mall-washington': 8,
    'rose-bowl-pasadena': 9,
    'tokyo-dome-tokyo': 9,
    'stonehenge-salisbury': 9,
    'great-pyramid-giza': 10,
    'colosseum-rome': 10,
    'estadio-azteca-mexico-city': 10,
