// XP is awarded per flagship show; the nonlinear curve makes sustained quality
// matter and keeps major card-size unlocks several strong seasons away.
const GM_LEVEL_THRESHOLDS = [
  { level: 1, experience: 0 },
  { level: 2, experience: 50 },
  { level: 3, experience: 110 },
  { level: 4, experience: 190 },
  { level: 5, experience: 300 },
  { level: 6, experience: 440 },
  { level: 7, experience: 610 },
  { level: 8, experience: 810 },
  { level: 9, experience: 1040 },
  { level: 10, experience: 1300 },
];

export function gmExperienceForShow(rating = 0) {
  const stars = Math.max(0, Math.min(5, (Number(rating) || 0) / 20));
  return Math.max(2, Math.round(stars * stars));
}

export function gmLevelForExperience(experience = 0) {
  return [...GM_LEVEL_THRESHOLDS].reverse().find(tier => experience >= tier.experience)?.level ?? 1;
}

export function experienceRequiredForLevel(level) {
  return GM_LEVEL_THRESHOLDS.find(tier => tier.level === level)?.experience ?? 0;
}

