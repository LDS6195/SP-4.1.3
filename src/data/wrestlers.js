export function momentumLabel(momentum) {
  if (momentum >= 3) return 'On Fire';
  if (momentum >= 1) return 'Hot';
  if (momentum === 0) return 'Steady';
  if (momentum >= -2) return 'Cold';
  return 'Ice Cold';
}

// Projects the "on paper" chemistry between two wrestlers using style fit, hidden
// synergy tags, scripted dream/mismatch pairings, alignment contrast, and momentum.
// Returns a 0-100 quality score plus short human-readable notes explaining why.
export function computeChemistry(idA, idB) {
  const a = getWrestlerById(idA);
  const b = getWrestlerById(idB);
  if (!a || !b || a.id === b.id) return null;

  let score = 50;
  const notes = [];

  const synergy = styleSynergy(a.style, b.style);
  if (synergy) {
    score += synergy;
    notes.push(synergy > 0 ? `${a.style} vs. ${b.style} is a proven crowd-pleasing contrast.` : `${a.style} vs. ${b.style} can feel repetitive.`);
  }

  const sharedTags = a.chemistryTags.filter(tag => b.chemistryTags.includes(tag));
  if (sharedTags.length) {
    score += sharedTags.length * 5;
    notes.push(`Shared style DNA: ${sharedTags.join(', ')}.`);
  }

  if (a.bestChemistryWith.includes(b.id) || b.bestChemistryWith.includes(a.id)) {
    score += 30;
    notes.push('Scouted as a dream pairing by the booking office.');
  }
  if (a.poorChemistryWith.includes(b.id) || b.poorChemistryWith.includes(a.id)) {
    score -= 30;
    notes.push('Flagged as an awkward stylistic mismatch.');
  }

  if (a.alignment !== b.alignment && a.alignment !== 'tweener' && b.alignment !== 'tweener') {
    score += 10;
    notes.push('Clean face vs. heel dynamic.');
  }

  if (a.momentum >= 2 && b.momentum >= 2) {
    score += 10;
    notes.push('Two hot streaks on a collision course — automatic hype.');
  } else if (a.momentum <= -2 && b.momentum <= -2) {
    score -= 5;
    notes.push('Two cold wrestlers rarely draw money together.');
  }

  score = Math.max(0, Math.min(100, Math.round(score)));
  return { score, notes };
}

export function topChemistryPartners(id, count = 3) {
  return wrestlers
    .filter(w => w.id !== id)
    .map(w => ({ wrestler: w, ...computeChemistry(id, w.id) }))
    .sort((x, y) => y.score - x.score)
    .slice(0, count);
}

// Draft-value bucket. Most wrestlers derive it from popularity; a few (special
// attractions) carry an explicit override because fame and roster value diverge.
export function getDraftTier(wrestler) {
  if (wrestler.draftTier) return wrestler.draftTier === 'prospect' ? 'contender' : wrestler.draftTier;
  if (wrestler.popularity >= 85) return 'legend';
  if (wrestler.popularity >= 70) return 'star';
  if (wrestler.popularity >= 35) return 'contender';
  return 'jobber';
}

// Some wrestlers (special attractions, future call-ups) are not in the world yet.
