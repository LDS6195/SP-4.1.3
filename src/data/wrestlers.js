export const matchHistory = [];

function opponentInMatch(match, id) {
  return match.wrestlerA === id ? match.wrestlerB : match.wrestlerA;
}

export function getMatchHistoryFor(id) {
  return matchHistory
    .filter(match => match.wrestlerA === id || match.wrestlerB === id)
    .map(match => {
      const opponentId = opponentInMatch(match, id);
      const opponent = getWrestlerById(opponentId);
      let result = 'D';
      if (match.winner === id) result = 'W';
      else if (match.winner === opponentId) result = 'L';
      else if (match.winner === 'no-contest') result = 'NC';
      return {
        date: match.date,
        event: match.event,
        opponentName: opponent ? opponent.name : 'Unknown',
        result,
        description: match.description,
      };
    })
    .sort((a, b) => new Date(b.date) - new Date(a.date));
}

export function getWrestlerById(id) {
  return wrestlers.find(w => w.id === id) || null;
}

export function createCustomWrestler(data, id, date = GAME_START_DATE) {
  const clean = (value, limit) => String(value ?? '').replace(/[<>&"]/g, '').trim().slice(0, limit);
  const name = clean(data.name, 32);
  const age = Number(data.age ?? 25);
  if (!name || !STYLES.includes(data.style) || !['face', 'heel'].includes(data.alignment)
    || !Number.isInteger(age) || age < 18 || age > 55) return null;
  const reference = new Date(`${date.slice(0, 10)}T12:00:00Z`);
  if (Number.isNaN(reference.getTime())) return null;
  reference.setUTCFullYear(reference.getUTCFullYear() - age);
  return {
    id, custom: true, name, nickname: clean(data.nickname, 32),
    alignment: data.alignment, style: data.style,
    hometown: clean(data.hometown, 64) || 'Parts Unknown',
    height: "6'0\"", weight: 230,
    dob: reference.toISOString().slice(0, 10), debutYear: Number(date.slice(0, 4)),
    bio: clean(data.bio, 400) || `${name} is an original signing ready to make their mark.`,
    signatureMoves: [clean(data.finisher, 48) || 'Running Lariat'],
    stats: { strength: 50, agility: 50, stamina: 50, technique: 50, charisma: 50, toughness: 50 },
    hidden: { ego: 50, workEthic: 65, riskTolerance: 50, lockerRoomImpact: 50 },
    chemistryTags: [], bestChemistryWith: [], poorChemistryWith: [],
    popularity: 45, momentum: 0,
    streak: { type: 'none', count: 0 }, record: { w: 0, l: 0 },
  };
}

export function calculateAge(dob, asOf = GAME_START_DATE) {
  const birth = new Date(dob);
  const reference = new Date(asOf);
  let age = reference.getFullYear() - birth.getFullYear();
  const monthDiff = reference.getMonth() - birth.getMonth();
  if (monthDiff < 0 || (monthDiff === 0 && reference.getDate() < birth.getDate())) age -= 1;
  return age;
}

